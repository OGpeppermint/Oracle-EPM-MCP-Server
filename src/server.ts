const activeOracleRequests = new Map<AbortController, Promise<unknown>>();

export async function closeOracleRequests(): Promise<void> {
  const pending = [...activeOracleRequests];
  for (const [controller] of pending) controller.abort();
  await Promise.allSettled(pending.map(([, request]) => request));
}

const connectionSchema = z.object({
  configured: z.boolean().describe("True only when all required Oracle EPM environment variables are present on the MCP server."),
  baseUrl: z.string().optional().describe("Configured Oracle Cloud EPM origin. The password and authorization header are never returned."),
  application: z.string().optional().describe("Configured Oracle EPM Planning application name, such as NSPB."),
  username: z.string().optional().describe("Masked service-account username for troubleshooting; this is never the password."),
  missing: z.array(z.string()).describe("Required server environment-variable names that are absent. Empty when configured is true."),
}).describe("Sanitized server-side Oracle EPM connection configuration status.");

const connectionOutputSchema = {
  connection: connectionSchema,
  checkedAt: z.string().describe("ISO 8601 timestamp generated by the MCP server when connection configuration was checked."),
};

const optionalApplication = z.string().trim().min(1).optional().describe("Oracle EPM Planning application name. Omit to use EPM_APPLICATION from the MCP server environment.");
const jsonDataOutputSchema = {
  data: z.json().describe("JSON response returned by the documented Oracle EPM Planning REST endpoint."),
};

const readAnnotations = {
  readOnlyHint: true,
  destructiveHint: false,
  idempotentHint: true,
  openWorldHint: true,
} as const;

class EpmHttpError extends Error {
  constructor(
    message: string,
    readonly status: number,
    readonly responseType?: string | null,
  ) {
    super(message);
    this.name = "EpmHttpError";
  }
}

function connectionStatus() {
  const values = {
    EPM_BASE_URL: process.env.EPM_BASE_URL?.replace(/\/$/, ""),
    EPM_USERNAME: process.env.EPM_USERNAME,
    EPM_PASSWORD: process.env.EPM_PASSWORD,
    EPM_APPLICATION: process.env.EPM_APPLICATION?.trim() || undefined,
  };
  const missing = (["EPM_BASE_URL", "EPM_USERNAME", "EPM_PASSWORD"] as const).filter((key) => !values[key]);
  return {
    configured: missing.length === 0,
    baseUrl: values.EPM_BASE_URL,
    application: values.EPM_APPLICATION,
    username: values.EPM_USERNAME ? values.EPM_USERNAME.replace(/^(.{2}).*(@.*)$/, "$1••••$2") : undefined,
    missing,
  };
}

async function epmRequest<T>(pathName: string, init?: RequestInit, accept = "application/json"): Promise<T> {
  const missing = ["EPM_BASE_URL", "EPM_USERNAME", "EPM_PASSWORD"].filter((key) => !process.env[key]);
  if (missing.length) throw new Error(`Oracle EPM authentication is not configured. Missing: ${missing.join(", ")}`);
  const auth = Buffer.from(`${process.env.EPM_USERNAME}:${process.env.EPM_PASSWORD}`).toString("base64");
  const headers = new Headers(init?.headers);
  headers.set("Authorization", `Basic ${auth}`);
  headers.set("Accept", accept);
  if (init?.body === undefined) headers.delete("Content-Type");
  else if (!headers.has("Content-Type")) headers.set("Content-Type", "application/json");
  const controller = new AbortController();
  const request = (async () => {
    const response = await fetch(`${process.env.EPM_BASE_URL}${pathName}`, {
      ...init,
      headers,
      signal: AbortSignal.any([AbortSignal.timeout(30_000), controller.signal]),
    });
    const body = await response.text();
    if (!response.ok) {
      const method = init?.method?.toUpperCase() ?? "GET";
      const responseType = response.headers.get("content-type");
      const typeDetails = responseType ? `; response content-type ${responseType}` : "";
      throw new EpmHttpError(
        `Oracle EPM ${method} ${pathName} returned ${response.status}${typeDetails}: ${body.slice(0, 500) || response.statusText}`,
        response.status,
        responseType,
      );
    }
    if (!body) return {} as T;
    const responseType = response.headers.get("content-type")?.toLowerCase() ?? "";
    if (responseType.includes("json")) return JSON.parse(body) as T;
    if (responseType.includes("text/plain") || responseType.includes("text/markdown")) return body as T;
    try {
      return JSON.parse(body) as T;
    } catch {
      throw new Error(`Oracle EPM returned an unsupported successful response content-type ${responseType || "unknown"} for ${pathName}.`);
    }
  })();
  activeOracleRequests.set(controller, request);
  try {
    return await request;
  } finally {
    activeOracleRequests.delete(controller);
  }
}

function configuredApplication(application?: string): string {
  const value = application?.trim() || process.env.EPM_APPLICATION?.trim();
  if (!value) throw new Error("No Oracle EPM application was provided and EPM_APPLICATION is not configured on the MCP server.");
  return value;
}

function planningPath(application: string | undefined, suffix = ""): string {
  return `/HyperionPlanning/rest/v3/applications/${encodeURIComponent(configuredApplication(application))}${suffix}`;
}

function withQuery(pathName: string, values: Record<string, string | number | undefined>): string {
  const query = new URLSearchParams();
  for (const [key, value] of Object.entries(values)) if (value !== undefined && value !== "") query.set(key, String(value));
  const encoded = query.toString();
  return encoded ? `${pathName}?${encoded}` : pathName;
}

async function applicationSummary(
  application?: string,
  fullHierarchyThreshold?: number,
  aliasTableName?: string,
  dimensionsToInclude?: string,
): Promise<unknown> {
  const effectiveAlias = aliasTableName?.toLowerCase() === "default" ? undefined : aliasTableName;
  const pathName = withQuery(planningPath(application, "/summary"), {
    fullHierarchyThreshold,
    aliasTableName: effectiveAlias,
    dimensionsToInclude,
  });
  try {
    return await epmRequest(pathName, { method: "GET" });
  } catch (error) {
    if (!(error instanceof EpmHttpError) || error.status !== 406) throw error;
    return epmRequest(pathName, { method: "GET" }, "*/*");
  }
}

async function apiResult(label: string, request: () => Promise<unknown>): Promise<CallToolResult> {
  try {
    const data = await request();
    return textResult(`${label} completed successfully.`, { data });
  } catch (error) {
    return textResult(error instanceof Error ? error.message : String(error), undefined, true);
  }
}

function textResult(text: string, structuredContent?: Record<string, unknown>, isError = false): CallToolResult {
  return { content: [{ type: "text", text }], structuredContent, isError };
}

function connectionData() {
  return { connection: connectionStatus(), checkedAt: new Date().toISOString() };
}

